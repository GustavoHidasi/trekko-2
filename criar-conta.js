let lang = localStorage.getItem("trekko-lang") || "pt";
function t(k) {
  return (I18N[lang] || I18N.pt)[k] || k;
}
function applyLang() {
  document.querySelectorAll("[data-i]").forEach((el) => {
    const k = el.getAttribute("data-i");
    if (I18N[lang] && I18N[lang][k]) el.textContent = I18N[lang][k];
  });
  document.querySelectorAll("[data-i-placeholder]").forEach((el) => {
    const k = el.getAttribute("data-i-placeholder");
    if (I18N[lang] && I18N[lang][k]) el.placeholder = I18N[lang][k];
  });
  document.querySelectorAll(".lang-select").forEach((s) => (s.value = lang));
}
function setLang(l) {
  lang = l;
  localStorage.setItem("trekko-lang", l);
  applyLang();
  document.querySelectorAll(".lang-select").forEach((s) => (s.value = l));
}
applyLang();

