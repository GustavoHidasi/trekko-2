// ── EMAIL SUGGESTION ──
const COMMON_DOMAINS = [
  "gmail.com",
  "hotmail.com",
  "yahoo.com",
  "outlook.com",
  "icloud.com",
  "live.com",
];
let suggestedEmail = "";
const _origValidateEmail = validateEmail;
validateEmail = function () {
  const result = _origValidateEmail();
  const val = document.getElementById("email").value.trim();
  const sug = document.getElementById("email-suggestion");
  const atIdx = val.lastIndexOf("@");
  if (atIdx > 0 && val.length > atIdx + 2) {
    const domain = val.slice(atIdx + 1).toLowerCase();
    const close = COMMON_DOMAINS.find((d) => {
      if (d === domain) return false;
      let diff = 0;
      const a = domain,
        b = d;
      for (let i = 0; i < Math.max(a.length, b.length); i++) {
        if (a[i] !== b[i]) diff++;
      }
      return diff <= 3 && diff > 0;
    });
    if (close) {
      suggestedEmail = val.slice(0, atIdx + 1) + close;
      sug.textContent = "Quis dizer " + suggestedEmail + "?";
      sug.classList.add("show");
    } else {
      sug.classList.remove("show");
    }
  } else {
    sug.classList.remove("show");
  }
  return result;
};
function applySuggestion() {
  document.getElementById("email").value = suggestedEmail;
  document.getElementById("email-suggestion").classList.remove("show");
  validateEmail();
  checkStep1();
}

