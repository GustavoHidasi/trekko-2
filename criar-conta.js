function maskCep(input) {
  let v = input.value.replace(/\D/g, "").slice(0, 8);
  if (v.length > 5) v = v.slice(0, 5) + "-" + v.slice(5);
  input.value = v;
  if (v.replace(/\D/g, "").length === 8) fetchCep(v.replace(/\D/g, ""));
}
async function fetchCep(cep) {
  const msg = document.getElementById("cep-msg");
  const cityState = document.getElementById("city-state");
  try {
    msg.className = "field-msg";
    msg.textContent = "Buscando...";
    msg.style.display = "block";
    msg.style.color = "var(--teal)";
    const r = await fetch("https://viacep.com.br/ws/" + cep + "/json/");
    const d = await r.json();
    if (d.erro) {
      msg.className = "field-msg error";
      msg.style.display = "block";
      msg.textContent = "CEP não encontrado";
      cityState.value = "";
    } else {
      msg.className = "field-msg success";
      msg.textContent = "✓ CEP encontrado";
      msg.style.display = "block";
      cityState.value = d.localidade + " / " + d.uf;
      toast("📍 " + d.localidade + " — " + d.uf, "success", 3000);
    }
  } catch (e) {
    msg.className = "field-msg error";
    msg.textContent = "Erro ao buscar CEP";
    msg.style.display = "block";
  }
}

