function goNext(step, forward) {
  goingForward = forward;
  const cur = document.getElementById("step-" + currentStep);
  cur.classList.add(forward ? "slide-out" : "");
  setTimeout(
    () => {
      cur.classList.remove("active", "slide-out");
      document.getElementById("step-" + step).classList.remove("slide-out");
      document
        .getElementById("step-" + step)
        .classList.add("active", forward ? "" : "slide-in-left");
      setTimeout(
        () =>
          document
            .getElementById("step-" + step)
            .classList.remove("slide-in-left"),
        400,
      );
      for (let i = 1; i <= 3; i++) {
        const c = document.getElementById("circle-" + i);
        c.classList.remove("active", "done");
        if (i < step) {
          c.classList.add("done");
          c.innerHTML = "✓";
        } else if (i === step) {
          c.classList.add("active");
          c.innerHTML = i;
        } else {
          c.innerHTML = i;
        }
      }
      document.getElementById("bar-1").classList.toggle("done", step >= 2);
      document.getElementById("bar-2").classList.toggle("done", step >= 3);
      document.getElementById("step-title").textContent = t(TITLES[step].title);
      document.getElementById("step-sub").textContent = t(TITLES[step].sub);
      currentStep = step;
      if (step === 2) checkStep2();
      if (step === 3) checkStep3();
    },
    forward ? 300 : 0,
  );
}

